const SKINS = ['#F6D2B8', '#E8B896', '#D19A6E', '#A8704A', '#73452A', '#4D2D1B'];
const HAIRS = ['#1B1717', '#3D2719', '#6C4727', '#B68A42', '#101419'];
const HAIR_STYLES: HairStyle[] = ['Curto', 'Moicano', 'BlackPower', 'Topete', 'Raspado', 'Tranças'];

const FORMATION_SLOTS: PositionId[] = [
  'GK_TRAD',
  'RB',
  'CB_STOPPER',
  'CB_BALL',
  'LB',
  'CDM_ANCHOR',
  'CM',
  'CAM',
  'RW',
  'ST',
  'LW',
];

function buildSquad(clubSeed: number, squadQuality: number): ClubSquadMember[] {
  return FORMATION_SLOTS.map((pos, idx) => {
    const fn = FIRST_NAMES[(clubSeed * 7 + idx * 3) % FIRST_NAMES.length];
    const ln = LAST_NAMES[(clubSeed * 11 + idx * 5) % LAST_NAMES.length];
    const variance = ((clubSeed + idx * 13) % 9) - 4;
    const ovr = Math.max(54, Math.min(88, squadQuality + variance));
    const isGK = pos === 'GK_TRAD';
    const isDef = pos === 'CB_STOPPER' || pos === 'CB_BALL' || pos === 'RB' || pos === 'LB';
    const isAtt = pos === 'ST' || pos === 'RW' || pos === 'LW' || pos === 'CAM';

    return {
      id: `npc_${clubSeed}_${idx}`,
      name: `${fn} ${ln}`,
      number: [1, 2, 3, 4, 6, 5, 8, 10, 7, 9, 11][idx],
      position: pos,
      ovr,
      skinColor: SKINS[(clubSeed + idx * 2) % SKINS.length],
      hairColor: HAIRS[(clubSeed + idx * 3) % HAIRS.length],
      hairStyle: HAIR_STYLES[(clubSeed + idx) % HAIR_STYLES.length],
      speed: Math.min(92, ovr + (pos === 'RW' || pos === 'LW' || pos === 'RB' || pos === 'LB' ? 6 : isGK ? -14 : 0)),
      passing: Math.min(92, ovr + (pos === 'CM' || pos === 'CAM' ? 7 : isGK ? -6 : 0)),
      shooting: Math.min(92, ovr + (isAtt ? 7 : isDef ? -10 : -15)),
      defending: Math.min(92, ovr + (isDef || pos === 'CDM_ANCHOR' ? 8 : isAtt ? -16 : -10)),
      dribbling: Math.min(92, ovr + (isAtt ? 6 : isGK ? -18 : -4)),
      gkSkill: isGK ? Math.min(92, ovr + 4) : 25,
    };
  });
}

